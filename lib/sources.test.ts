import assert from "node:assert/strict";
import { describe, test } from "vitest";
import { MAX_SOURCES, SOURCE_CHARS, isReadablePath, pickFiles, readableText } from "./sources";

describe("which files are worth reading", () => {
  test("lockfiles, build output, minified bundles and binaries are skipped by name", () => {
    for (const p of [
      "package-lock.json",
      "web/yarn.lock",
      "poetry.lock",
      "dist/index.js",
      "frontend/.next/server/app.js",
      "node_modules/x/index.js",
      "public/app.min.js",
      "logo.png",
      "models/classifier.gguf",
      "notebooks/train.ipynb",
      "src/__generated__/schema.ts",
      ".env",
      "backend/.env.local",
      ".env.production",
    ]) {
      assert.equal(isReadablePath(p), false, p);
    }
    for (const p of ["package.json", "backend/src/utils.js", "app/api/chat/route.ts", "requirements.txt", "backend/.env.example"]) {
      assert.equal(isReadablePath(p), true, p);
    }
  });

  test("binary, minified and generated contents are skipped; the rest is cut to SOURCE_CHARS", () => {
    assert.equal(readableText("PNG\u0000\u0001"), null);
    assert.equal(readableText("var a=1;".repeat(400)), null);
    assert.equal(readableText("// @generated by protoc\nexport const x = 1;"), null);
    assert.equal(readableText("x\n".repeat(SOURCE_CHARS))!.length, SOURCE_CHARS);
    assert.equal(readableText("const a = 1;\n"), "const a = 1;\n");
  });
});

describe("picking files", () => {
  test("every claim's first candidate comes before anyone's second", () => {
    assert.deepEqual(
      pickFiles([
        ["a.ts", "b.ts"],
        ["c.ts", "d.ts"],
      ]),
      ["a.ts", "c.ts", "b.ts", "d.ts"],
    );
  });

  test(`no repeats, nothing unreadable, at most ${MAX_SOURCES}`, () => {
    const many = Array.from({ length: 6 }, (_, i) => [`f${i}.ts`, `g${i}.ts`]);
    assert.equal(pickFiles(many).length, MAX_SOURCES);
    assert.deepEqual(pickFiles([["a.ts"], ["a.ts", "yarn.lock"]]), ["a.ts"]);
  });
});
